/**
 * The generated block of google-apps-script/service-pages.gs: the schema, the URL groups and the
 * settings the in-sheet refresh needs. `pnpm sheet:apps-script` rewrites it; the test fails when
 * the checked-in block no longer matches the schema.
 */
import fs from 'node:fs'
import path from 'node:path'
import hierarchy from '../../data/cluster-hierarchy.json'
import {PUBLIC_SITE_ORIGIN} from '../../src/lib/service-urls'
import {LIST_HEADROOM, META_COLUMNS, PAGE_TYPE, compactSchema} from './page-sheet'

export const APPS_SCRIPT_PATH = path.resolve('google-apps-script/service-pages.gs')
export const SHEET_TAB = 'Service Pages'
const START = '// <generated by pnpm sheet:apps-script>'
const END = '// </generated>'

type Cluster = {slug: string; parentName?: string; services: string[]}

export function appsScriptConfig() {
  const clusters = (hierarchy.clusters as Cluster[]).filter((cluster) => cluster.services.length > 0 || cluster.parentName)
  const query = `*[_type == "${PAGE_TYPE}" && !(_id in path("drafts.**"))]`
  return {
    tab: SHEET_TAB,
    // Published documents only: the dataset is public, so no token is needed (or stored in the sheet).
    queryUrl: `https://5w5623jq.api.sanity.io/v2025-02-19/data/query/production?perspective=published&query=${encodeURIComponent(query)}`,
    origin: PUBLIC_SITE_ORIGIN,
    nested: hierarchy.nestedServiceUrls === true,
    groups: {
      byService: Object.fromEntries(clusters.flatMap((cluster) => cluster.services.map((service) => [service, cluster.slug]))),
      byParentName: Object.fromEntries(clusters.flatMap((cluster) => (cluster.parentName ? [[cluster.parentName.trim().toLowerCase(), cluster.slug]] : []))),
    },
    meta: META_COLUMNS,
    headroom: LIST_HEADROOM,
    schema: compactSchema(),
  }
}

export const generatedBlock = () => `${START}\nconst SP_CONFIG = ${JSON.stringify(appsScriptConfig(), null, 1)}\n${END}`

/** The script with a fresh generated block. */
export function renderAppsScript(source = fs.readFileSync(APPS_SCRIPT_PATH, 'utf8')): string {
  const start = source.indexOf(START), end = source.indexOf(END)
  if (start < 0 || end < start) throw new Error(`${APPS_SCRIPT_PATH} has lost its generated markers`)
  return source.slice(0, start) + generatedBlock() + source.slice(end + END.length)
}
